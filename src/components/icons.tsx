/** Icon matching a column's data type (shared by the grid header, the column
 * builder and the add/edit column dialog). */
export function ColumnTypeIcon({ type, ...p }: IconProps & { type: ColumnType }) {
  switch (type) {
    case "number":
      return <IconHash {...p} />;
    case "date":
      return <IconCalendar {...p} />;
    case "checkbox":
      return <IconCheckSquare {...p} />;
    case "select":
      return <IconCircleDot {...p} />;
    case "multi_select":
      return <IconTags {...p} />;
    case "relation":
      return <IconLink {...p} />;
    case "formula":
      return <IconSigma {...p} />;
    default:
      return <IconType {...p} />;
  }
}