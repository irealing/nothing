// Global workspace state. All backend calls go through src/ipc (AGENTS.md);
// failures are caught here, mirrored into `error` (inline forms) and pushed to
// the toast stack (transient feedback).
//
// Rows are loaded lazily in windows (PAGE_SIZE pages) so 100k-row tables
// scroll smoothly: `rowsCache` maps absolute row index → Row, `total` is the
// full match count, and `dataVersion` invalidates everything on writes.

import { errorText, t } from "../i18n";
import { create } from "zustand";
import * as ipc from "../ipc";
import { toast } from "./toast";
import type {
  Cells,
  ColumnColor,
  ColumnMeta,
  ColumnPatch,
  GridConfig,
  ImportCsvOptions,
  ImportReport,
  Json,
  NewColumn,
  NewView,
  RecentWorkspace,
  Row,
  RowPage,
  SqlResult,
  TableMeta,
  ViewData,
  ViewMeta,
  ViewPatch,
  WorkspaceInfo,
  WorkspaceUiState,
} from "../types";
import { colType, isReverse } from "../types";

export const PAGE_SIZE = 200;

/**
 * Cells to copy when duplicating a row. Formula columns are generated by the
 * database and reverse relation columns are the other side of an existing
 * link, so neither can be written back.
 */
export function duplicateCells(row: Row, columns: ColumnMeta[]): Cells {
  const cells: Cells = {};
  for (const col of columns) {
    if (colType(col) === "formula" || isReverse(col)) continue;
    const value = row.cells[col.id];
    if (value !== undefined) cells[col.id] = value;
  }
  return cells;
}

/** File name part of a path (workspaces are identified by it in the UI). */
export function baseName(path: string): string {
  const parts = path.split(/[\\/]/);
  return parts[parts.length - 1] || path;
}

/** Windows paths are case-insensitive; POSIX ones are not. */
export function samePath(a: string, b: string): boolean {
  const norm = (p: string) => {
    const unified = p.replace(/\\/g, "/");
    return /^[a-zA-Z]:\//.test(unified) ? unified.toLowerCase() : unified;
  };
  return norm(a) === norm(b);
}

export function defaultGridConfig(): GridConfig {
  return { filters: null, sorts: [] };
}

/** What the row window pipeline currently reads from. */
type Source =
  | { kind: "none" }
  | { kind: "view"; viewId: string }
  | { kind: "table"; tableId: string }
  | { kind: "search"; tableId: string; query: string };

interface WorkspaceState {
  info: WorkspaceInfo | null;
  tables: TableMeta[];
  activeTableId: string | null;
  /** All columns of the active table (panels, dialogs). */
  columns: ColumnMeta[];
  /** Columns the current source actually returns (view-hidden applied). */
  visibleColumns: ColumnMeta[];
  /** Grid views of the active table + workspace-level SQL views. */
  views: ViewMeta[];
  activeViewId: string | null;

  // recent files (from the plain-text settings file, not the encrypted db)
  lastWorkspace: RecentWorkspace | null;
  recent: RecentWorkspace[];
  /** A `.nothing` path the shell asked us to open (file association). */
  pendingPath: string | null;
  /** Settings and any queued open request have been loaded. */
  booted: boolean;

  // windowed row data
  source: Source;
  total: number;
  rowsCache: Map<number, Row>;
  /** Bumped whenever rowsCache/total change — TableView re-renders on it. */
  rowsVersion: number;
  /** Bumped on any write; in-flight fetches with an older version are dropped. */
  dataVersion: number;
  /** rid → title, accumulated across fetched windows. */
  titles: Record<string, string>;

  sqlResult: SqlResult | null;
  searchQuery: string;
  /** Session-only scratch SQL console; never written to the workspace file. */
  scratch: { open: boolean; statement: string };
  loading: boolean;
  error: string | null;

  // windowed loading
  fetchWindow: (start: number, end: number) => Promise<void>;

  // workspace lifecycle
  boot: () => Promise<void>;
  requestPath: (path: string | null) => void;
  openWorkspace: (path: string, password: string) => Promise<void>;
  createWorkspace: (path: string, password: string) => Promise<void>;
  closeWorkspace: () => Promise<void>;
  changePassword: (pw: string) => Promise<void>;
  clearError: () => void;

  // navigation
  selectTable: (id: string) => Promise<void>;
  selectView: (viewId: string | null) => Promise<void>;
  refresh: () => Promise<void>;

  // scratch read-only SQL console
  openScratch: () => void;
  closeScratch: () => void;
  setScratchStatement: (statement: string) => void;

  // tables & columns
  createTable: (name: string, columns: NewColumn[], icon?: string | null) => Promise<void>;
  importCsv: (options: ImportCsvOptions) => Promise<ImportReport | null>;
  deleteTable: (id: string) => Promise<void>;
  renameTable: (id: string, name: string) => Promise<void>;
  setTableIcon: (id: string, icon: string | null) => Promise<void>;
  setTableColor: (id: string, color: ColumnColor | null) => Promise<void>;
  setTitleColumn: (colId: string) => Promise<void>;
  /** Resolves false when the backend rejected the change; the reason is in `error`. */
  addColumn: (col: NewColumn) => Promise<boolean>;
  updateColumn: (colId: string, patch: ColumnPatch) => Promise<boolean>;
  deleteColumn: (colId: string) => Promise<void>;

  // views
  createGridView: (name: string) => Promise<void>;
  createSqlView: (name: string, statement: string) => Promise<void>;
  updateView: (viewId: string, patch: ViewPatch) => Promise<void>;
  updateViewColumn: (
    viewId: string,
    columnId: string,
    patch: { width?: number; position?: number; hidden?: boolean },
  ) => Promise<void>;
  deleteView: (viewId: string) => Promise<void>;

  // rows
  insertRow: (cells?: Cells) => Promise<void>;
  /** Append several rows in one write cycle (paste / import paths). */
  insertRows: (rows: Cells[]) => Promise<void>;
  duplicateRows: (rids: string[]) => Promise<void>;
  updateCell: (rid: string, colId: string, value: Json) => Promise<void>;
  /** Batched cell writes (Delete range, paste) with a single refetch. */
  updateCells: (updates: { rid: string; cells: Cells }[]) => Promise<void>;
  deleteRows: (rids: string[]) => Promise<void>;
  searchRows: (query: string) => Promise<void>;
}

async function guard<R>(
  set: (p: Partial<WorkspaceState>) => void,
  get: () => WorkspaceState,
  fn: () => Promise<R>,
): Promise<R | undefined> {
  set({ loading: true, error: null });
  try {
    return await fn();
  } catch (e) {
    const message = errorText(e);
    set({ error: message });
    toast.error(message);
    return undefined;
  } finally {
    set({ loading: false });
    void get;
  }
}

export const useWorkspace = create<WorkspaceState>((set, get) => {
  /** Fetch one aligned page from the current source into the cache. */
  async function fetchPage(source: Source, offset: number, version: number): Promise<void> {
    let gridPage: RowPage;
    switch (source.kind) {
      case "view": {
        const res = await ipc.viewRun(source.viewId, PAGE_SIZE, offset);
        if (res.kind !== "grid") return; // sql views don't page
        gridPage = res;
        break;
      }
      case "table":
        gridPage = await ipc.rowList(source.tableId, PAGE_SIZE, offset);
        break;
      case "search":
        gridPage = await ipc.search(source.tableId, source.query, PAGE_SIZE, offset);
        break;
      case "none":
        return;
    }
    // Drop stale responses (a write happened while we were in flight).
    if (get().dataVersion !== version) return;
    const cache = get().rowsCache;
    gridPage.rows.forEach((r, i) => cache.set(offset + i, r));
    set({
      total: gridPage.total,
      visibleColumns: gridPage.columns,
      titles: { ...get().titles, ...gridPage.titles },
      rowsVersion: get().rowsVersion + 1,
    });
  }

  async function fetchWindowInternal(start: number, end: number) {
    const { source, total, rowsCache, dataVersion } = get();
    if (source.kind === "none") return;
    const from = Math.max(0, Math.floor(start / PAGE_SIZE) * PAGE_SIZE);
    // Upper bound: known total when available, otherwise just the request.
    const to = total > 0 ? Math.min(end, total) : end;
    const inflight: Promise<void>[] = [];
    for (let p = from; p < to; p += PAGE_SIZE) {
      // Skip pages already fully cached (bounded by total when known).
      const pageEnd = total > 0 ? Math.min(p + PAGE_SIZE, total) : p + PAGE_SIZE;
      let complete = true;
      for (let i = p; i < pageEnd; i++) {
        if (!rowsCache.has(i)) {
          complete = false;
          break;
        }
      }
      if (!complete) inflight.push(fetchPage(source, p, dataVersion));
    }
    await Promise.all(inflight);
  }

  /** Reset row state and prime the first window for a new source. */
  async function prime(source: Source) {
    set((s) => ({
      source,
      rowsCache: new Map(),
      total: 0,
      titles: {},
      dataVersion: s.dataVersion + 1,
      rowsVersion: s.rowsVersion + 1,
    }));
    await fetchWindowInternal(0, PAGE_SIZE);
  }

  /** Refresh the recent-file snapshot from the settings file. */
  async function syncSettings() {
    try {
      const s = await ipc.settingsGet();
      if (!s) return;
      set({ lastWorkspace: s.last_workspace ?? null, recent: s.recent ?? [] });
    } catch {
      // Settings are a convenience: never surface a failure here.
    }
  }

  /** Last table/view for a workspace, or null when unknown/stale. */
  async function loadUi(path: string): Promise<WorkspaceUiState | null> {
    try {
      return (await ipc.settingsUi(path)) ?? null;
    } catch {
      return null;
    }
  }

  /** Remember the active table/view for the open workspace. */
  async function persistUi() {
    const { info, activeTableId, activeViewId } = get();
    if (!info || !activeTableId) return;
    try {
      await ipc.settingsSetUi(info.path, activeTableId, activeViewId);
    } catch {
      // Presentation-only; a failure must not interrupt navigation.
    }
  }

  /** Load columns + views for a table and activate a view (Notion-style:
   * every table always has at least one grid view). */
  async function loadTableData(tableId: string, viewId: string | null) {
    const [columns, views] = await Promise.all([
      ipc.columnList(tableId),
      ipc.viewList(tableId),
    ]);
    set({ columns, views, activeViewId: viewId, sqlResult: null, searchQuery: "" });
    // Record the choice before running the view: if the query itself fails the
    // selection is still the one the user made, and reopening retries it.
    await persistUi();
    if (viewId) {
      const view = views.find((v) => v.id === viewId);
      if (view?.kind === "sql") {
        const result = await ipc.viewRun(viewId, 1000, 0);
        if (result.kind === "sql") {
          set({ sqlResult: result, source: { kind: "none" }, rowsCache: new Map(), total: 0 });
          return;
        }
      }
      if (view?.kind === "grid") {
        await prime({ kind: "view", viewId });
        return;
      }
    }
    await prime({ kind: "table", tableId });
  }

  async function activateTable(tableId: string, preferredViewId: string | null = null) {
    const columns = await ipc.columnList(tableId);
    let views = await ipc.viewList(tableId);
    set({
      activeTableId: tableId,
      columns,
      views,
      searchQuery: "",
      scratch: { ...get().scratch, open: false },
    });
    let gridViews = views.filter((v) => v.kind === "grid");
    if (gridViews.length === 0) {
      await ipc.viewCreate({
        table_id: tableId,
        name: t("view.defaultName"),
        kind: "grid",
        data: { kind: "grid", ...defaultGridConfig() },
      } satisfies NewView);
      views = await ipc.viewList(tableId);
      set({ views });
      gridViews = views.filter((v) => v.kind === "grid");
    }
    // Restored selection wins when it still exists; otherwise the first grid view.
    const preferred = preferredViewId ? views.find((v) => v.id === preferredViewId) : undefined;
    await loadTableData(tableId, preferred?.id ?? gridViews[0]?.id ?? null);
  }

  /** Window title mirrors the open file so the taskbar is meaningful. */
  function syncTitle(info: WorkspaceInfo | null) {
    if (typeof document === "undefined") return;
    document.title = info ? `${baseName(info.path)} — nothing` : "nothing";
  }

  /** After a write: drop the cache and re-prime the current source. */
  async function afterWrite() {
    const { activeTableId, activeViewId, searchQuery } = get();
    if (!activeTableId) return;
    if (searchQuery) {
      await prime({ kind: "search", tableId: activeTableId, query: searchQuery });
      return;
    }
    const view = get().views.find((v) => v.id === activeViewId);
    if (view?.kind === "sql") {
      const result = await ipc.viewRun(view.id, 1000, 0);
      if (result.kind === "sql") set({ sqlResult: result });
      return;
    }
    if (view?.kind === "grid") {
      await prime({ kind: "view", viewId: view.id });
      return;
    }
    await prime({ kind: "table", tableId: activeTableId });
  }

  return {
    info: null,
    tables: [],
    activeTableId: null,
    columns: [],
    visibleColumns: [],
    views: [],
    activeViewId: null,
    lastWorkspace: null,
    recent: [],
    pendingPath: null,
    booted: false,
    source: { kind: "none" },
    total: 0,
    rowsCache: new Map(),
    rowsVersion: 0,
    dataVersion: 0,
    titles: {},
    sqlResult: null,
    searchQuery: "",
    scratch: { open: false, statement: "SELECT " },
    loading: false,
    error: null,

    fetchWindow: async (start, end) => {
      // High-frequency (scroll) path: no global loading flag, errors only
      // surface via toast; identical consecutive messages collapse.
      try {
        await fetchWindowInternal(start, end);
      } catch (e) {
        const message = errorText(e);
        set({ error: message });
        toast.error(message);
      }
    },

    clearError: () => set({ error: null }),

    boot: async () => {
      await syncSettings();
      // A cold start with a file association queues the path in Rust; take it
      // now so the welcome screen can unlock straight away.
      try {
        const pending = await ipc.takeOpenRequest();
        if (pending) set({ pendingPath: pending });
      } catch {
        // No request is a fine outcome.
      }
      set({ booted: true });
    },

    requestPath: (path) => set({ pendingPath: path }),

    openWorkspace: async (path, password) => {
      await guard(set, get, async () => {
        const info = await ipc.workspaceOpen(path, password);
        const tables = await ipc.tableList();
        set({
          info,
          tables,
          activeTableId: null,
          columns: [],
          visibleColumns: [],
          views: [],
          rowsCache: new Map(),
          total: 0,
          titles: {},
          sqlResult: null,
          source: { kind: "none" },
          pendingPath: null,
          scratch: { open: false, statement: "SELECT " },
        });
        syncTitle(info);
        // The core just recorded this open; mirror it locally so closing the
        // workspace immediately still shows the right "last opened" entry.
        await syncSettings();
        if (tables.length > 0) {
          const ui = await loadUi(info.path);
          const table = tables.find((x) => x.id === ui?.table_id) ?? tables[0];
          await activateTable(table.id, ui?.view_id ?? null);
        }
      });
    },

    createWorkspace: async (path, password) => {
      await guard(set, get, async () => {
        const info = await ipc.workspaceCreate(path, password);
        set({
          info,
          tables: [],
          activeTableId: null,
          columns: [],
          visibleColumns: [],
          views: [],
          rowsCache: new Map(),
          total: 0,
          titles: {},
          sqlResult: null,
          searchQuery: "",
          source: { kind: "none" },
          pendingPath: null,
          scratch: { open: false, statement: "SELECT " },
        });
        syncTitle(info);
        await syncSettings();
      });
    },

    closeWorkspace: async () => {
      await guard(set, get, async () => {
        await ipc.workspaceClose();
        set({
          info: null,
          tables: [],
          activeTableId: null,
          columns: [],
          visibleColumns: [],
          views: [],
          activeViewId: null,
          rowsCache: new Map(),
          total: 0,
          titles: {},
          sqlResult: null,
          searchQuery: "",
          source: { kind: "none" },
          scratch: { open: false, statement: "SELECT " },
        });
        syncTitle(null);
      });
    },

    changePassword: async (pw) => {
      await guard(set, get, async () => {
        await ipc.workspaceChangePassword(pw);
        toast.success(t("toasts.passwordChanged"));
      });
    },

    selectTable: async (id) => {
      await guard(set, get, () => activateTable(id));
    },

    selectView: async (viewId) => {
      const { activeTableId } = get();
      if (!activeTableId) return;
      await guard(set, get, async () => {
        set((s) => ({ scratch: { ...s.scratch, open: false } }));
        await loadTableData(activeTableId, viewId);
      });
    },

    refresh: async () => {
      await guard(set, get, async () => {
        set({ tables: await ipc.tableList() });
        await afterWrite();
      });
    },

    openScratch: () => set((s) => ({ scratch: { ...s.scratch, open: true } })),
    closeScratch: () => set((s) => ({ scratch: { ...s.scratch, open: false } })),
    setScratchStatement: (statement) =>
      set((s) => ({ scratch: { ...s.scratch, statement } })),

    createTable: async (name, columns, icon) => {
      await guard(set, get, async () => {
        const t = await ipc.tableCreate(name, columns, icon);
        set({ tables: await ipc.tableList() });
        await activateTable(t.id);
      });
    },

    importCsv: async (options) => {
      // Returns the report so the dialog can show counts; on failure the
      // existing toast carries the error and the dialog stays open.
      set({ loading: true, error: null });
      try {
        const report = await ipc.csvImport(options);
        set({ tables: await ipc.tableList() });
        await activateTable(report.table.id);
        return report;
      } catch (e) {
        const message = errorText(e);
        set({ error: message });
        toast.error(message);
        return null;
      } finally {
        set({ loading: false });
      }
    },

    deleteTable: async (id) => {
      await guard(set, get, async () => {
        const name = get().tables.find((x) => x.id === id)?.name ?? "";
        await ipc.tableDelete(id);
        const tables = await ipc.tableList();
        set({ tables });
        if (get().activeTableId === id) {
          const next = tables[0]?.id ?? null;
          set({
            activeTableId: next,
            columns: [],
            visibleColumns: [],
            views: [],
            rowsCache: new Map(),
            total: 0,
            titles: {},
            sqlResult: null,
            source: { kind: "none" },
          });
          if (next) await activateTable(next);
        }
        if (name) toast.success(t("toasts.tableDeleted", { name }));
      });
    },

    renameTable: async (id, name) => {
      await guard(set, get, async () => {
        await ipc.tableRename(id, name);
        set({ tables: await ipc.tableList() });
      });
    },

    setTableIcon: async (id, icon) => {
      await guard(set, get, async () => {
        await ipc.tableSetIcon(id, icon);
        // Presentation-only: refresh the table list, don't refetch rows.
        set({ tables: await ipc.tableList() });
      });
    },

    setTableColor: async (id, color) => {
      await guard(set, get, async () => {
        await ipc.tableSetColor(id, color);
        set({ tables: await ipc.tableList() });
      });
    },

    setTitleColumn: async (colId) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return;
        await ipc.tableSetTitle(activeTableId, colId);
        set({ tables: await ipc.tableList() });
        await afterWrite();
      });
    },

    addColumn: async (col) => {
      const ok = await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return false;
        await ipc.columnAdd(activeTableId, col);
        set({ columns: await ipc.columnList(activeTableId) });
        await afterWrite();
        return true;
      });
      return ok === true;
    },

    updateColumn: async (colId, patch) => {
      const ok = await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return false;
        await ipc.columnUpdate(activeTableId, colId, patch);
        const columns = await ipc.columnList(activeTableId);
        set({ columns });
        // Type/options changes can alter stored values; position/visibility
        // change which columns the current source returns. Both need a fresh
        // page from the backend.
        const affectsData = patch.type !== undefined || patch.choices !== undefined;
        const affectsShape = patch.position !== undefined;
        if (affectsData || affectsShape) {
          await afterWrite();
        } else {
          // Metadata-only (rename/icon/color/align/default/width): refresh the
          // rendered columns in place so headers update immediately.
          set((s) => ({
            visibleColumns: s.visibleColumns.map(
              (c) => columns.find((next) => next.id === c.id) ?? c,
            ),
            rowsVersion: s.rowsVersion + 1,
          }));
        }
        return true;
      });
      return ok === true;
    },

    deleteColumn: async (colId) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return;
        const name = get().columns.find((c) => c.id === colId)?.name ?? "";
        await ipc.columnDelete(activeTableId, colId);
        set({ columns: await ipc.columnList(activeTableId) });
        await afterWrite();
        if (name) toast.success(t("toasts.columnDeleted", { name }));
      });
    },

    createGridView: async (name) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return;
        const v = await ipc.viewCreate({
          table_id: activeTableId,
          name,
          kind: "grid",
          data: { kind: "grid", ...defaultGridConfig() },
        });
        await loadTableData(activeTableId, v.id);
      });
    },

    createSqlView: async (name, statement) => {
      await guard(set, get, async () => {
        const v = await ipc.viewCreate({
          table_id: null,
          name,
          kind: "sql",
          data: { kind: "sql", statement },
        });
        const { activeTableId } = get();
        if (activeTableId) {
          set({ views: await ipc.viewList(activeTableId), activeViewId: v.id });
        }
        const result = await ipc.viewRun(v.id, 1000, 0);
        if (result.kind === "sql") {
          set({ sqlResult: result, source: { kind: "none" }, rowsCache: new Map(), total: 0 });
        }
        await persistUi();
      });
    },

    updateView: async (viewId, patch) => {
      await guard(set, get, async () => {
        await ipc.viewUpdate(viewId, patch);
        const { activeTableId, activeViewId } = get();
        if (!activeTableId) return;
        if (activeViewId === viewId) {
          await loadTableData(activeTableId, viewId);
        } else {
          set({ views: await ipc.viewList(activeTableId) });
        }
      });
    },

    updateViewColumn: async (viewId, columnId, patch) => {
      await guard(set, get, async () => {
        await ipc.viewColumnUpdate(viewId, columnId, patch);
        const { activeTableId, activeViewId } = get();
        if (!activeTableId) return;
        set({ views: await ipc.viewList(activeTableId) });
        // Width/hidden/order all change what the grid returns.
        if (activeViewId === viewId) await afterWrite();
      });
    },

    deleteView: async (viewId) => {
      await guard(set, get, async () => {
        const name = get().views.find((v) => v.id === viewId)?.name ?? "";
        await ipc.viewDelete(viewId);
        const { activeTableId, activeViewId } = get();
        if (!activeTableId) return;
        if (activeViewId === viewId) {
          await activateTable(activeTableId);
        } else {
          set({ views: await ipc.viewList(activeTableId) });
        }
        if (name) toast.success(t("toasts.viewDeleted", { name }));
      });
    },

    insertRow: async (cells = {}) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return;
        await ipc.rowInsert(activeTableId, cells);
        await afterWrite();
      });
    },

    insertRows: async (rows) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId || rows.length === 0) return;
        for (const cells of rows) await ipc.rowInsert(activeTableId, cells);
        await afterWrite();
      });
    },

    duplicateRows: async (rids) => {
      await guard(set, get, async () => {
        const { activeTableId, columns } = get();
        if (!activeTableId || rids.length === 0) return;
        for (const rid of rids) {
          const row = await ipc.rowGet(activeTableId, rid);
          await ipc.rowInsert(activeTableId, duplicateCells(row, columns));
        }
        await afterWrite();
      });
    },

    updateCell: async (rid, colId, value) => {
      await guard(set, get, async () => {
        const { activeTableId, activeViewId, searchQuery } = get();
        if (!activeTableId) return;
        const updated = await ipc.rowUpdate(activeTableId, rid, { [colId]: value });
        // Patch in place first for instant feedback (formula cells included —
        // the backend returns the recomputed row)…
        const cache = get().rowsCache;
        for (const [idx, r] of cache) {
          if (r.rid === rid) {
            cache.set(idx, { ...r, ...updated });
            break;
          }
        }
        set((s) => ({ rowsVersion: s.rowsVersion + 1 }));

        // …then only revalidate when the edit can change membership, ordering
        // or related titles: filtered/sorted views, active search, or relation
        // columns (their pills resolve through the backend title map). Plain
        // edits in an unfiltered grid keep the in-place patch authoritative,
        // so typing in a cell no longer refetches the page and flickers.
        const col = get().columns.find((c) => c.id === colId);
        const view = get().views.find((v) => v.id === activeViewId);
        const cfg = view?.data.kind === "grid" ? view.data : null;
        const stable =
          !searchQuery && (cfg === null || (cfg.filters === null && cfg.sorts.length === 0));
        if (!stable || (col && colType(col) === "relation")) {
          await afterWrite();
        }
      });
    },

    deleteRows: async (rids) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId) return;
        await ipc.rowDelete(activeTableId, rids);
        await afterWrite();
      });
    },

    updateCells: async (updates) => {
      await guard(set, get, async () => {
        const { activeTableId } = get();
        if (!activeTableId || updates.length === 0) return;
        const batch: [string, Cells][] = updates.map((u) => [u.rid, u.cells]);
        await ipc.rowBatchUpdate(activeTableId, batch);
        await afterWrite();
      });
    },

    searchRows: async (query) => {
      await guard(set, get, async () => {
        const { activeTableId, activeViewId } = get();
        if (!activeTableId) return;
        if (!query) {
          set({ searchQuery: "" });
          await loadTableData(activeTableId, activeViewId);
          return;
        }
        set({ searchQuery: query, sqlResult: null });
        await prime({ kind: "search", tableId: activeTableId, query });
      });
    },
  };
});

export type { GridConfig, ViewData };
